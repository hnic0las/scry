#!/usr/bin/env python3
"""Generates apps/macos/Scry/Theme/Colors.swift from the design's colour roles.

Reads ../git-scry-ui/prototype/tokens/colors.json (or the path given) and
writes one Color per role, resolved at draw time for light or dark
appearance and the colour-blind-safe palette. Version 2 groups are skipped.

    scripts/generate-theme.py [path/to/colors.json]
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else root.parent / "git-scry-ui/prototype/tokens/colors.json"
target = root / "apps/macos/Scry/Theme/Colors.swift"


def rgba(value):
    value = value.strip()
    if value == "transparent":
        return 0.0, 0.0, 0.0, 0.0
    if value.startswith("#"):
        digits = value[1:]
        r, g, b = (int(digits[i:i + 2], 16) / 255 for i in (0, 2, 4))
        a = int(digits[6:8], 16) / 255 if len(digits) == 8 else 1.0
        return r, g, b, a
    match = re.fullmatch(r"rgba?\(([^)]*)\)", value)
    if not match:
        raise ValueError(f"unsupported colour {value!r}")
    parts = [float(p) for p in match.group(1).split(",")]
    r, g, b = (p / 255 for p in parts[:3])
    return r, g, b, parts[3] if len(parts) > 3 else 1.0


def swift(value):
    return "RGBA(%.4f, %.4f, %.4f, %.4f)" % rgba(value)


# Role names that are Swift keywords need backticks.
KEYWORDS = {"operator", "default", "case", "class", "struct", "enum", "func", "import", "let", "var",
            "return", "self", "static", "protocol", "extension", "where", "in", "is", "as", "nil"}


def identifier(name):
    return f"`{name}`" if name in KEYWORDS else name


roles = json.loads(source.read_text())
lines = [
    "// Generated by scripts/generate-theme.py from git-scry-ui/prototype/tokens/colors.json.",
    "// Do not edit: change the design tokens, then run the script again.",
    "",
    "import SwiftUI",
    "",
    "extension Theme {",
]
for group, entries in roles.items():
    if group.startswith("$") or group.startswith("v2_") or not isinstance(entries, dict):
        continue
    lines.append(f"    enum {group[0].upper() + group[1:]} {{")
    for name, role in entries.items():
        if not isinstance(role, dict) or "light" not in role:
            continue
        use = role.get("use")
        if use:
            lines.append(f"        /// {use}")
        lines.append(
            f"        static let {identifier(name)} = Theme.color(\n"
            f"            light: {swift(role['light'])},\n"
            f"            dark: {swift(role['dark'])},\n"
            f"            colourBlindLight: {swift(role.get('colourBlindLight', role['light']))},\n"
            f"            colourBlindDark: {swift(role.get('colourBlindDark', role['dark']))}\n"
            f"        )"
        )
    lines.append("    }")
    lines.append("")
lines[-1] = "}"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(lines) + "\n")
print(f"wrote {target.relative_to(root)}")
